/**
 * High-speed, robust regex-based translator for jewelry terminology.
 */
export function translateFrenchToAr(text: string): string {
  if (!text || text.trim() === '') return '';

  let result = text.trim();

  // If text already consists mainly of Arabic characters
  const arabicMatches = result.match(/[\u0600-\u06FF]/g) || [];
  if (arabicMatches.length > result.length * 0.4) {
    return result;
  }

  // Apply dictionary replacements
  for (const [regex, replacement] of DICTIONARY) {
    result = result.replace(regex, replacement);
  }

  return result;
}
